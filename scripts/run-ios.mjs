import { spawn, spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { delimiter, resolve } from 'node:path';

import { rustEnvironment } from './lib/rust-environment.mjs';

// Thin wrapper around `tauri ios <args>`, mirroring run-tauri.mjs: it runs from
// apps/studio (where src-tauri lives) with the repo-local Rust toolchain on PATH.
//
// This repo pins a hermetic toolchain under .toolchains/ rather than a global
// rustup. Xcode's generated "Build Rust Code" phase runs `cargo` from its own
// sandboxed environment and does not see CARGO_HOME/RUSTUP_HOME, so it falls
// back to an (empty) ~/.rustup and fails with "no default toolchain". We keep
// the generated gen/apple/project.yml pointed at .toolchains/ so the build
// phase always resolves the repo toolchain. gen/apple is regenerated by
// `tauri ios init`, so we (re)apply the bridge here, idempotently.
const root = resolve(import.meta.dirname, '..');
const { env } = await rustEnvironment(root);
// Homebrew tools (xcodegen, pod, tauri's libimobiledevice) live here.
env.PATH = `/opt/homebrew/bin${delimiter}${env.PATH ?? ''}`;

function ensureToolchainBridge() {
  const genApple = resolve(root, 'apps/studio/src-tauri/gen/apple');
  const projectYml = resolve(genApple, 'project.yml');
  if (!existsSync(projectYml)) return; // not initialised yet (e.g. `ios init`)
  let yml = readFileSync(projectYml, 'utf8');
  if (yml.includes('RUSTUP_HOME')) return; // already bridged
  const patched = yml.replace(
    /( *)- script: (pnpm tauri ios xcode-script[^\n]*)/,
    (_match, indent, command) => {
      const body = `${indent}    `;
      return [
        `${indent}- script: |`,
        `${body}REPO_ROOT="$(cd "$SRCROOT" && git rev-parse --show-toplevel)"`,
        `${body}export CARGO_HOME="$REPO_ROOT/.toolchains/cargo"`,
        `${body}export RUSTUP_HOME="$REPO_ROOT/.toolchains/rustup"`,
        `${body}export PATH="$CARGO_HOME/bin:$PATH"`,
        `${body}${command}`,
      ].join('\n');
    },
  );
  if (patched === yml) return; // template changed shape — leave it, surface later
  writeFileSync(projectYml, patched);
  // Regenerate the .xcodeproj from the patched project.yml.
  spawnSync('xcodegen', ['generate'], { cwd: genApple, env, stdio: 'inherit' });
  console.error('[run-ios] applied .toolchains bridge to gen/apple/project.yml');
}

const subcommand = process.argv[2];
if (subcommand === 'dev' || subcommand === 'build') {
  ensureToolchainBridge();
}

const child = spawn('pnpm', ['exec', 'tauri', 'ios', ...process.argv.slice(2)], {
  cwd: resolve(root, 'apps/studio'),
  env,
  stdio: 'inherit',
});
child.on('error', (error) => {
  console.error(error);
  process.exitCode = 1;
});
child.on('exit', (code, signal) => {
  process.exitCode = code ?? (signal ? 1 : 0);
});
