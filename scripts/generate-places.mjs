// Generates packages/rhythm/src/places-data.js — a compact, offline place
// gazetteer used by the rhythm profile's birthplace picker so a person never
// has to know their own latitude/longitude.
//
// Build-time only. `all-the-cities` (GeoNames, CC BY 4.0) supplies name /
// country / coordinates / population; `tz-lookup` derives the IANA timezone
// on-device. The output is a plain TSV string with one row per place, sorted
// by population descending so the picker's first matches are the most
// populous. Neither dependency ships in the app — this script bakes their data
// into a committed asset that the app lazy-loads.
//
// Run with: node scripts/generate-places.mjs

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import cities from 'all-the-cities';
import tzLookup from 'tz-lookup';

const here = dirname(fileURLToPath(import.meta.url));
const outFile = join(here, '..', 'packages', 'rhythm', 'src', 'places-data.js');

/** Round to 3 decimals (~110 m) — far finer than a birthplace picker needs. */
function round3(n) {
  return Math.round(n * 1000) / 1000;
}

/** Names are free text; strip the two delimiters the TSV format reserves. */
function clean(name) {
  return name.replace(/[\t\n]/gu, ' ').trim();
}

const sorted = [...cities].sort((a, b) => b.population - a.population);

const rows = [];
for (const city of sorted) {
  const name = clean(city.name);
  if (name === '') continue;
  const [lon, lat] = city.loc.coordinates;
  let timeZone;
  try {
    timeZone = tzLookup(lat, lon);
  } catch {
    continue; // no resolvable zone (e.g. open ocean coordinate) — skip
  }
  rows.push(`${name}\t${city.country}\t${round3(lat)}\t${round3(lon)}\t${timeZone}`);
}

const banner =
  '// @generated by scripts/generate-places.mjs — do not edit by hand.\n' +
  '// Source: GeoNames via all-the-cities (CC BY 4.0); timezones via tz-lookup.\n' +
  '// One TSV row per place: name\\tcountryCode\\tlat\\tlon\\tianaTimeZone, sorted by population.\n';

const body = `export default ${JSON.stringify(rows.join('\n'))};\n`;

writeFileSync(outFile, banner + body);

const bytes = Buffer.byteLength(banner + body);
console.log(`Wrote ${rows.length} places to ${outFile} (${(bytes / 1_000_000).toFixed(1)} MB raw).`);
